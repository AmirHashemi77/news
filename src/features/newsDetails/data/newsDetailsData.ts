export function getNewsDetails(newsId: string) {
  const news = newsListData.find((item) => item.id === newsId || item.url === `/news/${newsId}`);

  if (!news) return undefined;

  return {
    ...news,
    category: news.tags[0],
    publisher: "خبرگزاری مهر",
    viewCount: viewCounts[news.id] ?? 0,
    body: [news.description, ...(articleBodies[news.id] ?? [])],
  };
}
